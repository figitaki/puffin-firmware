void updatePiano(bool active[12]){
  int xPos = 26;
  int yPos = 28;
  int hSpacing = 4;
  int vSpacing = 0;
  int radius = 3;
  for(int i = 0; i<5; i++){
    int vSpacing = 0;
    if(i == 1 || i == 3){ vSpacing = 6; }
    if(active[i]){
      display.fillCircle((hSpacing*i+xPos),yPos-vSpacing,radius,WHITE);
    } else {
      display.drawCircle((hSpacing*i+xPos),yPos-vSpacing,radius,WHITE);
    }
  }
  for(int i = 5; i<12; i++){
    int vSpacing = 0;
    if(i == 6 || i == 8 || i==10){ vSpacing = 6; }
    if(active[i]){
      display.fillCircle((hSpacing*i+xPos+4),yPos-vSpacing,radius,WHITE);
    } else {
      display.drawCircle((hSpacing*i+xPos+4),yPos-vSpacing,radius,WHITE);
    }
  }
}

void displayFirmwareUpdate(const char *pin, const uint8_t status[12]) {
  display.clearDisplay();
  display.setFont(&Font5x7FixedMono);
  display.setTextSize(1);
  display.setTextColor(SSD1306_WHITE);
  display.setCursor(0, 8);
  display.print(String("UPDATE PIN ") + pin);
  display.setCursor(0, 19);
  if(status[1] == FirmwareUpdate::Receiving) {
    const uint32_t written = FirmwareUpdate::read32(status + 4);
    const uint32_t total = FirmwareUpdate::read32(status + 8);
    display.print(String(written / 1024) + "/" + String(total / 1024) + " KB");
    if(total) display.fillRect(0, 21, uint64_t(written) * 128 / total, 2, SSD1306_WHITE);
  } else if(status[1] == FirmwareUpdate::Complete) display.print("VERIFIED / RESTARTING");
  else if(status[1] == FirmwareUpdate::Error) display.print(String("ERROR ") + String(status[2]) + " / RESET");
  else if(status[1] == FirmwareUpdate::Authorized) display.print("PIN OK / READY");
  else display.print("READY / OPEN IOS APP");
  display.setCursor(0, 31);
  display.print("DEV: TRUSTED BIN ONLY");
  display.display();
}

bool displayProjectStatus(){
  if(!projectPrompt && (!projectNotice || uint32_t(millis() - projectNoticeAt) >= 5000)) return false;
  display.clearDisplay(); // Project confirmations use the entire small OLED.
  display.setFont(&Font5x7FixedMono);
  display.setTextSize(1);
  display.setCursor(0, 8);
  if(projectPrompt == PROJECT_LOAD) display.print("DISCARD EDITS?");
  else if(projectPrompt == PROJECT_INIT) display.print("ERASE STORAGE?");
  else if(projectPrompt == PROJECT_SAVE) display.print("REPLACE FILES?");
  else display.print(projectNotice);
  display.setCursor(0, 19);
  if(projectPrompt == PROJECT_INIT) display.print("ALL PROJECTS LOST");
  else if(projectPrompt == PROJECT_LOAD) display.print("LOAD LAST SAVE");
  else if(projectPrompt == PROJECT_SAVE) display.print("OLD SAVES OVERWRITE");
  else if(projectNotice && !strcmp(projectNotice, "STORAGE ERROR")) display.print("FN+C STORAGE SETUP");
  else display.print(projectDirty ? "UNSAVED *" : "SAVED");
  display.setCursor(0, 30);
  if(projectPrompt) display.print("FN+V YES / FN+B NO");
  else if(projectTransportPaused) display.print("START/CONT TO RESUME");
  else display.print("FN+Z SAVE / FN+X LOAD");
  return true;
}

void displayStepEditor(){
  display.setFont(&Font5x7FixedMono);
  display.setTextSize(1);
  display.setCursor(24, 8);
  display.print(String("T") + String(seq.selectedTrack() + 1) +
                (seq.muted() ? "M" : " ") + String(seq.editPage() + 1) + "/" + String(seq.pageCount()) +
                (chordEntry ? "+" : " ") + (seq.playing() ? ">" : "-"));
  uint8_t note = 0, velocity = 0;
  seq.getStep(seq.editStep(), note, velocity);
  const Sequencer::Step &value = *seq.getStep(seq.editStep());
  display.setCursor(24, 19);
  if(stepFull) display.print("FULL");
  else if(stepView == StepTrigger) {
    display.print(String("C") + String(value.chance) + " R" + String(value.ratchet) + " N" + String(value.count));
  } else if(stepView == StepControl) {
    int lockValue = -1;
    for(int i = 0; i < value.lockCount; ++i)
      if(value.locks[i].control == editControl) lockValue = value.locks[i].value;
    display.print(String(editControl) + "=" + (lockValue < 0 ? String("---") : String(lockValue)) +
                  " L" + String(value.lockCount));
  } else {
    display.print(String(seq.editStep() + 1) + "/" + String(seq.length()) + " " +
                  (value.count > 1 ? String(value.count) + "N" :
                   velocity ? String("N") + String(note) : String("REST")));
  }
  display.setCursor(88, 19);
  display.print(clk.getBPM() ? String(clk.getBPM()) : String("--"));
  display.setCursor(108, 19);
  display.print(clk.source() == Clock::Internal ? "INT" : clk.source() == Clock::BLE ? "BLE" : "TRS");

  const int first = seq.editPage() * Sequencer::StepsPerPage;
  for(int index = first; index < first + Sequencer::StepsPerPage && index < seq.length(); ++index) {
    const int x = 24 + (index - first) * 6;
    seq.getStep(index, note, velocity);
    if(velocity) display.fillRect(x + 1, 26, 3, 3, SSD1306_WHITE);
    else if(seq.getStep(index)->lockCount) display.drawRect(x + 1, 26, 3, 3, SSD1306_WHITE);
    else display.drawPixel(x + 2, 29, SSD1306_WHITE);
    if(index == seq.editStep()) display.drawRect(x, 24, 6, 7, SSD1306_WHITE);
    // The tick marks the next playback step, not the independently selected edit step.
    if(seq.playing() && index == seq.nextStep()) display.drawFastVLine(x + 2, 22, 2, SSD1306_WHITE);
  }
}

